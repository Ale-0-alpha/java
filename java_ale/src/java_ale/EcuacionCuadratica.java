package java_ale;

public class EcuacionCuadratica {
//ecuacion cuadratica 
public static void main(String[]args) {
int a = 1, b = -5, c = 6;
double x1,x2;
x1 = (-b + Math.sqrt(b*b-4*a*c))/(2*a);
x2 = (-b - Math.sqrt(b*b-4*a*c))/(2*a);
System.out.println("x1: " + x1);
System.out.println("x2: " + x2);






}
}
